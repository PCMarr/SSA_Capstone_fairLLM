def extract_article_data(url):
    """Extract main text and publish date from an article using newspaper3k."""
    try:
        article = Article(url)
        article.download()
        article.parse()
        text = article.text.strip()
        published_date = article.publish_date
        return text, published_date
    except Exception as e:
        print(f"Error parsing {url}: {e}")
        return "", None

def export_articles_to_json(df, output_file="harvested_articles.json"):
    """
    Extract article text + date and append to JSON file.
    Includes title, source_name, category, summary, published, text, and link.
    """

    # Load existing JSON data if file exists
    if os.path.exists(output_file):
        with open(output_file, "r", encoding="utf-8") as f:
            try:
                existing_articles = json.load(f)
            except json.JSONDecodeError:
                existing_articles = []
    else:
        existing_articles = []

    # Build set of (title, source_name) to detect duplicates
    existing_ids = set(
        (art.get("title", "").strip(), art.get("source_name", "").strip())
        for art in existing_articles
    )

    new_articles = []
    for _, row in df.iterrows():
        key = (row.get("title", "").strip(), row.get("source_name", "").strip())
        if key in existing_ids:
            continue  # Skip duplicate

        text, article_date = extract_article_data(row.get("link", ""))

        # Use feed date if available; otherwise use newspaper3k's date
        published = (
            row.get("published")
            if pd.notnull(row.get("published"))
            else article_date
        )

        # Normalize to ISO string
        if isinstance(published, datetime):
            published_str = published.isoformat()
        elif published:
            published_str = str(published)
        else:
            published_str = ""

        article_entry = {
            "title": row.get("title", ""),
            "source_name": row.get("source_name", ""),
            "category": row.get("category", ""),
            "summary": row.get("summary", ""),
            "published": published_str,
            "text": text,
            "link": row.get("link", "")
        }

        new_articles.append(article_entry)
        existing_ids.add(key)

    if not new_articles:
        print("⚠️ No new articles to add (all duplicates).")
        return

    # Append and write back to file
    all_articles = existing_articles + new_articles
    with open(output_file, "w", encoding="utf-8") as f:
        json.dump(all_articles, f, ensure_ascii=False, indent=2)

    print(f"✅ Added {len(new_articles)} new articles. Total: {len(all_articles)} in {output_file}")

DEFAULT_LIMIT = 30
def harvest(sources_table, include_categories=None, limit=DEFAULT_LIMIT, days_back=30):
    include_categories = set(include_categories or [])
    rows = []
    cutoff = datetime.now() - timedelta(days=days_back)
    for _, row in sources_table.iterrows():
        if include_categories and row['category'] not in include_categories:
            continue
        entries = fetch_feed(row['rss'], limit=limit)
        for e in entries:
            if e['published'] and e['published'] < cutoff:
                continue
            e['source_name'] = row['name']
            e['category'] = row['category']
            rows.append(e)
    if not rows:
        return pd.DataFrame(columns=['published','title','source_name','category','summary','link','feed'])
    df = pd.DataFrame(rows)
    df = df.sort_values(by=['published'], ascending=False, na_position='last').reset_index(drop=True)
    return df

