"""## 2) Helpers: Fetch Feeds, Normalize, Optional Summaries

These functions help with the IR task.

- `fetch_feed` — downloads RSS entries
- `clean_text` — small sanitizer
- `fetch_article_text` — attempts to extract full text using `trafilatura` first, then `newspaper3k`
- `summarize_text` — naive summary via sentence scoring (length + keyword hits)
"""

import math, time, html

def clean_text(t: str) -> str:
    if not t:
        return ''
    t = html.unescape(t)
    t = re.sub(r'<[^>]+>', ' ', t)
    t = re.sub(r'\s+', ' ', t).strip()
    return t

def fetch_feed(feed_url: str, limit: int = 50):
    try:
        fp = feedparser.parse(feed_url)
        entries = []
        for e in fp.entries[:limit]:
            title = clean_text(getattr(e, 'title', ''))
            link = getattr(e, 'link', '')
            summary = clean_text(getattr(e, 'summary', ''))
            published = None
            if getattr(e, 'published_parsed', None):
                published = datetime(*e.published_parsed[:6])
            elif getattr(e, 'updated_parsed', None):
                published = datetime(*e.updated_parsed[:6])
            entries.append({
                'title': title,
                'link': link,
                'summary': summary,
                'published': published,
                'source': urlparse(feed_url).netloc,
                'feed': feed_url,
            })
        return entries
    except Exception as ex:
        print('Feed error:', feed_url, ex)
        return []

def fetch_article_text(url: str, timeout: int = 15):
    text = ''
    # Try trafilatura first
    if trafilatura is not None:
        try:
            downloaded = trafilatura.fetch_url(url, timeout=timeout)
            if downloaded:
                text = trafilatura.extract(downloaded) or ''
        except Exception:
            pass
    # Fallback to newspaper3k
    if not text and Article is not None:
        try:
            art = Article(url)
            art.download()
            art.parse()
            text = art.text or ''
        except Exception:
            pass
    return clean_text(text)

def summarize_text(text: str, query_terms=None, max_sentences=4):
    if not text:
        return ''
    sents = re.split(r'(?<=[.!?])\s+', text)
    if not sents:
        return text[:400] + '...'
    query_terms = [t.lower() for t in (query_terms or []) if t.strip()]
    scores = []
    for i, s in enumerate(sents):
        length_score = min(len(s) / 200, 1.0)
        term_score = sum(s.lower().count(q) for q in query_terms)
        scores.append((length_score + term_score, i, s))
    scores.sort(reverse=True)
    chosen = [s for _, _, s in scores[:max_sentences]]
    chosen.sort(key=lambda x: sents.index(x))
    return ' '.join(chosen)

